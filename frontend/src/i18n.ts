// 按宿主 locale 精确/前缀解析到字典：zh-TW 优先繁体，其余 zh* 落简体。
const dicts: Record<string, Dict> = {
  'zh-cn': zhCN, 'zh-tw': zhTW, zh: zhCN,
  'en-us': en, 'en': en,
  'ja-jp': ja, 'ja': ja,
  'de-de': de, 'de': de,
  'ru-ru': ru, 'ru': ru,
}

import { hostPrefs } from './hostPrefs'

function resolveDict(locale: string): { primary: Dict; fallback: Dict } {
  const lower = locale.toLowerCase()
  if (dicts[lower]) return { primary: dicts[lower], fallback: en }
  const prefix = lower.split('-')[0]
  if (dicts[prefix]) return { primary: dicts[prefix], fallback: en }
  return { primary: en, fallback: zhCN }
}

export function t(key: string, params?: Record<string, string | number>): string {
  const { primary, fallback } = resolveDict(hostPrefs.locale)
  let s = primary[key] ?? fallback[key] ?? zhCN[key] ?? key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(`{${k}}`, String(v))
    }
  }
  return s
}

/** AntD 组件库的 locale 标识（main.tsx 用）。 */
export function antdLocaleKey(): 'zh_CN' | 'zh_TW' | 'en_US' | 'ja_JP' | 'de_DE' | 'ru_RU' {
  const lower = hostPrefs.locale.toLowerCase()
  if (lower.startsWith('zh')) return lower.startsWith('zh-tw') || lower.startsWith('zh-hant') ? 'zh_TW' : 'zh_CN'
  if (lower.startsWith('ja')) return 'ja_JP'
  if (lower.startsWith('de')) return 'de_DE'
  if (lower.startsWith('ru')) return 'ru_RU'
  return 'en_US'
}
